// Word-timed caption data for a cartoon film: node tools/film_words.mjs <asr_words.json> <lines.json> <out.ts> [--shift sec]
// asr_words.json = [{s,e,w}]; lines.json = [{role, text}] where the concatenated corrected tokens must equal the ASR token count (times come from the ASR).
// Writes: LINES (caption lines with word onsets), and per-role speaking intervals (SPEECH[role] = [{from,to}]).
import fs from 'node:fs';
const cutsFile = (process.argv.includes('--cuts') ? process.argv[process.argv.indexOf('--cuts') + 1] : '');
const CUTS = cutsFile ? JSON.parse(fs.readFileSync(cutsFile, 'utf8')) : [];
const cutsTs = `export const CUTS: [number, number][] = ${JSON.stringify(CUTS)};
// T: original-source seconds → film seconds (pauses were shortened);  O: film seconds → original-source seconds
export const T = (t: number) => t - CUTS.reduce((a, [x, y]) => a + (t <= x ? 0 : Math.min(t, y) - x), 0);
export const O = (u: number) => { let rem = 0, out = u; for (const [x, y] of CUTS) { if (u >= x - rem) out += y - x; rem += y - x; } return out; };
`;

const [asrF, linesF, outF] = process.argv.slice(2);
const asr = JSON.parse(fs.readFileSync(asrF, 'utf8'));
const lines = JSON.parse(fs.readFileSync(linesF, 'utf8'));
// a token written `word*2` spans 2 ASR tokens (the ASR split one spoken word in two)
const tokens = lines.flatMap((l, li) => l.text.trim().split(/\s+/).map((t) => { const m = t.match(/^(.+)\*(\d+)$/); return {t: m ? m[1] : t, n: m ? +m[2] : 1, li, role: l.role}; }));
const total = tokens.reduce((a, k) => a + k.n, 0);
if (total !== asr.length) { console.error(`token count ${total} != ASR ${asr.length}`); console.error(asr.map((a, i) => i + ':' + a.w).join(' ')); process.exit(1); }
const r2 = (n) => Math.round(n * 100) / 100;
let ai = 0;
const words = tokens.map((k) => { const a = asr[ai], b = asr[ai + k.n - 1]; ai += k.n; return {t: k.t.replace(/[؟?،,.!:]/g, '').replace(/~/g, ' '), raw: k.t, at: r2(a.s), to: r2(Math.max(b.e, a.s + 0.12)), li: k.li, role: k.role}; });
const L = lines.map((l, li) => ({role: l.role, words: words.filter((w) => w.li === li).map(({t, at, to}) => ({t, at, to}))}));
const speech = {};
for (const l of L) { (speech[l.role] ??= []).push({from: r2(l.words[0].at - 0.04), to: r2(l.words[l.words.length - 1].to + 0.05)}); }
fs.writeFileSync(outF, cutsTs + `// generated by tools/film_words.mjs\nexport const LINES = ${JSON.stringify(L.map((l) => ({words: l.words})))};\nexport const SPEECH: Record<string, {from: number; to: number}[]> = ${JSON.stringify(speech)};\nexport const ROLES = ${JSON.stringify(L.map((l) => l.role))};\n`);
console.log('ok', words.length, 'words', Object.entries(speech).map(([k, v]) => k + ':' + v.length).join(' '));

// «متى تستخدمه» — the user's usage field of each gallery element, made binding (user 2026-11-02: «أشعر أنك ما تأخذ منها وتعتمدها»).
//   node tools/element_usage.mjs sync     → data/element_usage.json = every element's usage text (the user's own `when` from data/gallery_notes.json wins over the
//                                           default `where` of data/elements_lab.json / TransitionsLab), plus `keep` / `drop` marks, stamped with the notes' hash
//   node tools/element_usage.mjs check    → fails when the notes changed after the last sync (so a stale usage list can never be used), and when an element marked
//                                           «احذفه» still exists in src/ (the cancelled-means-deleted rule)
//   node tools/element_usage.mjs list     → prints «العنصر: متى يُستعمل» for the plan (read it BEFORE writing a montage plan; every item is used where it says)
// The plan lists, for each element whose usage text matches a moment of the video, that it was used there, or why not (rules: PREFERENCES.md «متى يُستعمل كل عنصر»).
import fs from "node:fs";
import crypto from "node:crypto";

const NOTES = "data/gallery_notes.json", LAB = "data/elements_lab.json", OUT = "data/element_usage.json";
const read = (f, d) => { try { return JSON.parse(fs.readFileSync(f, "utf8")); } catch { return d; } };
const notes = read(NOTES, {}), lab = read(LAB, []);
const hash = crypto.createHash("sha1").update(JSON.stringify(Object.entries(notes).map(([id, v]) => [id, v.when ?? "", v.status ?? ""]).sort())).digest("hex").slice(0, 12);
const TL = fs.readFileSync("src/TransitionsLab.tsx", "utf8");
const where = new Map(lab.map((m) => [m.id, m.where]));
for (const m of TL.matchAll(/^  (\w+): \{ ar: "[^"]+", kit: "[^"]+", where: "([^"]+)"/gm)) where.set(m[1], m[2]);

const build = () => {
  const items = {};
  for (const id of new Set([...where.keys(), ...Object.keys(notes)])) {
    const n = notes[id] ?? {};
    const when = (n.when ?? "").trim() || where.get(id) || "";
    items[id] = { when, fromUser: !!(n.when ?? "").trim(), ...(n.status ? { mark: n.status } : {}) };
  }
  return { _: "Generated by tools/element_usage.mjs sync from the gallery's «متى تستخدمه» field (the user's text wins). Do not edit by hand.", hash, items };
};
const cmd = process.argv[2];
if (cmd === "sync") {
  const o = build(); fs.writeFileSync(OUT, JSON.stringify(o, null, 1));
  console.log(`element_usage: ${Object.keys(o.items).length} elements, ${Object.values(o.items).filter((v) => v.fromUser).length} with the user's own text → ${OUT}`);
} else if (cmd === "check") {
  const cur = read(OUT, null); let bad = 0;
  if (!cur || cur.hash !== hash) { console.log("✘ element_usage: ملاحظات المعرض تغيّرت بعد آخر مزامنة — شغّل node tools/element_usage.mjs sync ثم نفّذ ما جاء فيها"); bad++; }
  const src = fs.readdirSync("src").filter((f) => /\.tsx?$/.test(f)).map((f) => fs.readFileSync("src/" + f, "utf8")).join("\n");
  const retired = read("data/retired_elements.json", { components: [] }).components;
  for (const [id, n] of Object.entries(notes)) if (n.status === "drop" && !retired.includes(id) && new RegExp(`export const ${id}\\b`).test(src)) { console.log(`✘ element_usage: «${id}» معلَّم «احذفه» وكوده ما زال في src/ — احذفه وأضفه إلى data/retired_elements.json`); bad++; }
  console.log(bad ? `FAIL (${bad})` : "✔ element_usage: قائمة الاستعمال مطابقة لملاحظات المعرض ولا عنصر محذوف بقي");
  process.exit(bad ? 1 : 0);
} else if (cmd === "list") {
  const o = read(OUT, null) ?? build();
  console.log(Object.entries(o.items).filter(([, v]) => v.when && v.mark !== "drop").map(([id, v]) => `${id}${v.fromUser ? " ★" : ""}: ${v.when.replace(/\s+/g, " ")}`).join("\n"));
} else { console.error("usage: node tools/element_usage.mjs sync|check|list"); process.exit(2); }

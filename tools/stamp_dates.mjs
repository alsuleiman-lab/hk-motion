// Stamp each composition with its recency (newest first in Remotion Studio): node tools/stamp_dates.mjs
// For every <Composition id=… component={C}> in src/Root.tsx it takes the newest modification time among C's source file (found through the import line) and writes src/compositionDates.ts.
// Compositions that are NOT in that file (brand-new ones) show at the very top until the next stamp. Run again after adding / finishing a composition (tools/set_title.mjs does it automatically).
import fs from "node:fs";
import path from "node:path";
const root = fs.readFileSync("src/Root.tsx", "utf8").split("\r\n").join("\n");
const imports = {};
for (const m of root.matchAll(/import\s*\{([^}]+)\}\s*from\s*"(\.\/[^"]+)"/g)) for (const n of m[1].split(",")) imports[n.trim().split(/\s+as\s+/).pop()] = m[2];
const out = {};
for (const m of root.matchAll(/<Composition\b[^>]*?\bid="([^"]+)"[^>]*?\bcomponent=\{(\w+)\}/g)) {
  const rel = imports[m[2]]; let t = 0;
  if (rel) for (const ext of [".tsx", ".ts"]) { const p = path.join("src", rel + ext); if (fs.existsSync(p)) { t = Math.max(t, fs.statSync(p).mtimeMs); } }
  out[m[1]] = Math.round(t);
}
const body = Object.entries(out).sort((a, b) => b[1] - a[1]).map(([k, v]) => `  ${JSON.stringify(k)}: ${v},`).join("\n");
fs.writeFileSync("src/compositionDates.ts", `/** AUTO-GENERATED by tools/stamp_dates.mjs — recency (ms) per composition id; Studio lists newest first. Do not edit by hand. */\nexport const COMPOSITION_DATES: Record<string, number> = {\n${body}\n};\n`);
console.log(`stamped ${Object.keys(out).length} compositions`);

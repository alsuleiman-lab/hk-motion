// Render cost of every gallery element (user order 2026-11-08: «كل عنصر كم يستغرق… كم يؤخر المونتاج في صنعه وفي رندرته»).
// Renders the SAME 90 frames of each element alone (LabScene, scratch/lab_probe/index.tsx) at fixed settings and writes the milliseconds per frame,
// minus the baseline (the same scene with NO element = his clip + theme only), to data/element_costs.json (read by tools/gallery_build.mjs and tools/element_report.mjs).
//   node tools/element_bench.mjs [--repeat 2] [--only Id,Id] [--orient land|port|both] [--c 6]
// One render at a time (render lock). The minimum of the repeats is kept (the machine is shared with other sessions: min = least disturbed).
process.env.ENTRY = "scratch/lab_probe/index.tsx";
import fs from "node:fs"; import os from "node:os";
const { renderMedia, selectComposition } = await import("@remotion/renderer");
const { nvencOverride } = await import("./nvenc.mjs");
const { acquireRenderLock } = await import("./render_lock.mjs");
const { cachedServeUrl, privateTemp } = await import("./lib/cached_bundle.mjs");

privateTemp("elbench");
const argv = process.argv.slice(2);
const opt = (n, d) => (argv.includes("--" + n) ? argv[argv.indexOf("--" + n) + 1] : d);
const repeat = Number(opt("repeat", "2")), conc = Number(opt("c", "6")), orient = opt("orient", "both");
const only = opt("only", "").split(",").filter(Boolean);
const FR = 90, OUT = "data/element_costs.json";
const lab = JSON.parse(fs.readFileSync("data/elements_lab.json", "utf8"));
const prev = (() => { try { return JSON.parse(fs.readFileSync(OUT, "utf8")); } catch { return { items: {} }; } })();
acquireRenderLock("فحص كلفة العناصر");
try { os.setPriority(0, os.constants.priority.PRIORITY_BELOW_NORMAL); } catch { /* ignore */ }
fs.mkdirSync(".tmp/elbench", { recursive: true });
const { serveUrl } = await cachedServeUrl("LabLand", { tag: "elbench" });

const comps = {};
for (const o of ["land", "port"]) { const id = o === "land" ? "LabLand" : "LabPort"; comps[o] = { id, comp: await selectComposition({ serveUrl, id, inputProps: { id: "Word" } }) }; }
const one = async (o, id) => {
  const out = `.tmp/elbench/${o}_${id}.mp4`, t0 = Date.now();
  try {
    await renderMedia({ composition: comps[o].comp, serveUrl, inputProps: { id }, codec: "h264", crf: 18, muted: true, frameRange: [0, FR - 1], outputLocation: out, concurrency: conc,
      chromiumOptions: { gl: "angle" }, hardwareAcceleration: "if-possible", ffmpegOverride: nvencOverride, timeoutInMilliseconds: 120000, onProgress: () => {} });
    return (Date.now() - t0) / FR;
  } catch (e) { console.log("✘", o, id, String(e.message ?? e).split("\n")[0].slice(0, 100)); return null; }
  finally { try { fs.unlinkSync(out); } catch { /* ignore */ } }
};
const best = {};   // o|id -> min ms/frame
const orients = orient === "both" ? ["land", "port"] : [orient];
const list = ["__none", ...lab.map((m) => m.id)].filter((id) => !only.length || id === "__none" || only.includes(id));
await one("land", "__none");   // warm-up (fonts, GPU, bundle caches): discarded
for (let r = 0; r < repeat; r++) {
  for (const id of list) for (const o of orients) {
    const m = lab.find((x) => x.id === id);
    if (m && m.orient && m.orient !== "both" && m.orient !== o) continue;
    const ms = await one(o, id); if (ms == null) continue;
    const k = o + "|" + id; best[k] = Math.min(best[k] ?? 1e9, ms);
    console.log(`#${r + 1} ${o} ${id.padEnd(18)} ${ms.toFixed(0).padStart(5)} ms/frame`);
  }
}
const base = { land: best["land|__none"] ?? 0, port: best["port|__none"] ?? 0 };
const items = { ...(prev.items ?? {}) };
for (const m of lab) {
  const it = { ...(items[m.id] ?? {}) };
  for (const o of orients) { const v = best[o + "|" + m.id]; if (v != null) { it[o + "Ms"] = Math.round(v); it[o + "Extra"] = Math.round(v - base[o]); } }
  if (Object.keys(it).length) items[m.id] = it;
}
const out = { _: "Generated by tools/element_bench.mjs: ms per frame of 90 frames of the element alone (NVENC, concurrency " + conc + ", angle), Extra = minus the empty scene. Do not edit by hand.",
  at: new Date().toISOString(), frames: FR, concurrency: conc, repeat, baseline: { ...(prev.baseline ?? {}), ...Object.fromEntries(orients.map((o) => [o, Math.round(base[o])])) }, items };
fs.writeFileSync(OUT, JSON.stringify(out, null, 1));
console.log(`element_bench: ${Object.keys(items).length} elements → ${OUT}; baseline ${JSON.stringify(out.baseline)}`);

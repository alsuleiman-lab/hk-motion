// Word-timed caption data straight from an ASR word list (good MSA narration): node tools/film_words_auto.mjs <asr.json> <out.ts> --roles "A:29.6-35.1,B:38-43.3" [--default N] [--fix "bad=good,bad2=good2"] [--end 113.9]
// Words not inside any role range belong to the default role (the off-screen narrator). Writes LINES (caption lines), SPEECH[role] = intervals, ROLES.
import fs from 'node:fs';
const cutsFile = (process.argv.includes('--cuts') ? process.argv[process.argv.indexOf('--cuts') + 1] : '');
const CUTS = cutsFile ? JSON.parse(fs.readFileSync(cutsFile, 'utf8')) : [];
const cutsTs = `export const CUTS: [number, number][] = ${JSON.stringify(CUTS)};
// T: original-source seconds → film seconds (pauses were shortened);  O: film seconds → original-source seconds
export const T = (t: number) => t - CUTS.reduce((a, [x, y]) => a + (t <= x ? 0 : Math.min(t, y) - x), 0);
export const O = (u: number) => { let rem = 0, out = u; for (const [x, y] of CUTS) { if (u >= x - rem) out += y - x; rem += y - x; } return out; };
`;

const [asrF, outF, ...rest] = process.argv.slice(2);
const opt = (n, d) => (rest.includes('--' + n) ? rest[rest.indexOf('--' + n) + 1] : d);
const asr = JSON.parse(fs.readFileSync(asrF, 'utf8'));
const def = opt('default', 'N');
const ranges = (opt('roles', '') || '').split(',').filter(Boolean).map((s) => { const [r, a] = s.split(':'); const [x, y] = a.split('-').map(Number); return {r, x, y}; });
const fix = Object.fromEntries((opt('fix', '') || '').split(',').filter(Boolean).map((s) => s.split('=')));
const r2 = (n) => Math.round(n * 100) / 100;
const words = asr.map((a) => {
  const raw = a.w.trim(); const t = raw.replace(/[؟?،,.!:]/g, '');
  const mid = (a.s + a.e) / 2; const rg = ranges.find((g) => mid >= g.x && mid < g.y);
  return {t: fix[t] ?? t, at: r2(a.s), to: r2(Math.max(a.e, a.s + 0.12)), role: a.r ?? (rg ? rg.r : def), brk: /[؟?.!]$/.test(raw)};
});
const lines = []; let cur = null;
for (const w of words) {
  if (!cur || cur.role !== w.role || w.at - cur.words[cur.words.length - 1].to > 0.55 || cur.brkPrev || cur.words.length >= 9) { cur = {role: w.role, words: [], brkPrev: false}; lines.push(cur); }
  cur.words.push({t: w.t, at: w.at, to: w.to}); cur.brkPrev = w.brk;
}
const speech = {};
for (const l of lines) {
  const a = l.words[0].at - 0.04, b = l.words[l.words.length - 1].to + 0.05; const arr = (speech[l.role] ??= []); const last = arr[arr.length - 1];
  if (last && a - last.to < 0.5) last.to = r2(b); else arr.push({from: r2(a), to: r2(b)});
}
fs.writeFileSync(outF, cutsTs + `// generated by tools/film_words_auto.mjs\nexport const LINES = ${JSON.stringify(lines.map((l) => ({words: l.words})))};\nexport const SPEECH: Record<string, {from: number; to: number}[]> = ${JSON.stringify(speech)};\nexport const ROLES = ${JSON.stringify(lines.map((l) => l.role))};\n`);
console.log('ok', words.length, 'words', lines.length, 'lines', Object.entries(speech).map(([k, v]) => k + ':' + v.length).join(' '));
